#!/usr/bin/env python3
"""Generate assets/css/tokens.css from design/*.tokens.json.

The design system (Toynbee Convector) is the single source of truth for
colours, type, spacing, radius and shadow. Run this after copying a new
tokens.json from the design system:

    python3 scripts/tokens_to_css.py

Each colour theme in tokens.json becomes a [data-theme="<id>"] block.
The first theme is also the default on :root.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "toynbee-convector.tokens.json"
OUT = ROOT / "assets" / "css" / "tokens.css"

NAME_OK = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$")


def css_value(v):
    v = str(v)
    alias = re.fullmatch(r"\{([A-Za-z0-9_.-]+)\}", v)
    if alias:
        return f"var(--{alias.group(1)})"
    if any(c in v for c in ";{}<>"):
        raise ValueError(f"unsafe token value: {v!r}")
    return v


def px(v):
    return f"{v}px" if isinstance(v, (int, float)) else str(v)


def main():
    t = json.loads(SRC.read_text())
    themes = [th["id"] for th in t["color"]["themes"]]
    lines = [f"/* {t['name']} tokens. GENERATED by scripts/tokens_to_css.py from {SRC.name}. Do not edit by hand. */"]

    def theme_block(selector, theme_id):
        out = [f"{selector} {{"]
        for tok in t["color"]["tokens"]:
            name = tok["name"]
            assert NAME_OK.match(name), name
            val = tok["value"]
            if isinstance(val, dict):
                val = val.get(theme_id, val.get(themes[0]))
            out.append(f"  --{name}: {css_value(val)};")
        out.append("}")
        return out

    lines += theme_block(f':root, [data-theme="{themes[0]}"]', themes[0])
    for th in themes[1:]:
        lines += theme_block(f'[data-theme="{th}"]', th)

    lines.append(":root {")
    for fam, stack in t["type"]["families"].items():
        lines.append(f"  --font-{fam}: {css_value(stack)};")
    for fam_name in ("spacing", "radius", "shadow"):
        for tok in t.get(fam_name, {}).get("tokens", []):
            assert NAME_OK.match(tok["name"]), tok["name"]
            lines.append(f"  --{tok['name']}: {css_value(tok['value'])};")
    lines.append("}")

    # Text styles as utility classes (.masthead, .headline, .deck, .body, .caption, .label)
    for group in t["type"]["groups"]:
        fam = group["family"]
        for st in group["styles"]:
            decl = [f"font-family: var(--font-{fam})"]
            decl.append(f"font-size: {px(st['fontSize'])}")
            lh = st.get("lineHeight")
            if lh is not None:
                decl.append(f"line-height: {lh if isinstance(lh, (int, float)) and lh < 4 else px(lh)}")
            if "fontWeight" in st:
                decl.append(f"font-weight: {st['fontWeight']}")
            if "fontStyle" in st:
                decl.append(f"font-style: {st['fontStyle']}")
            if "letterSpacing" in st:
                decl.append(f"letter-spacing: {st['letterSpacing']}")
            lines.append(f".{st['name']} {{ {'; '.join(decl)}; }}")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(themes)} theme(s): {', '.join(themes)})")


if __name__ == "__main__":
    main()
